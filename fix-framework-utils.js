const fs = require('fs');
const path = require('path');

const utilsSrcDir = path.join(__dirname, 'src', 'utils');

const ts = require('typescript');

if (fs.existsSync(utilsSrcDir)) {
  const frameworks = ['svelte', 'vue', 'solid', 'angular'];
  
  frameworks.forEach(fw => {
    const utilsDistDir = path.join(__dirname, 'dist', fw, 'src', 'utils');
    fs.mkdirSync(utilsDistDir, { recursive: true });
    
    for (const utilFile of fs.readdirSync(utilsSrcDir).filter((f) => f.endsWith('.ts'))) {
      const srcCode = fs.readFileSync(path.join(utilsSrcDir, utilFile), 'utf8');
      fs.writeFileSync(path.join(utilsDistDir, utilFile), srcCode);
      const res = ts.transpileModule(srcCode, {
        compilerOptions: {
          target: ts.ScriptTarget.ES2020,
          module: ts.ModuleKind.ESNext,
          esModuleInterop: true
        }
      });
      fs.writeFileSync(path.join(utilsDistDir, utilFile.replace('.ts', '.js')), res.outputText);
    }
    console.log(`Copied and compiled src/utils/*.ts into dist/${fw}/src/utils/.`);
  });
}

// Clean up unused `_index` / `const index = _index();` in Solid component For loops
// generated by Mitosis to prevent CodeQL and TypeScript unused-variable warnings.
function fixSolidUnusedIndex(dir) {
  if (!fs.existsSync(dir)) return;
  for (const file of fs.readdirSync(dir).filter(f => f.endsWith('.tsx') || f.endsWith('.jsx'))) {
    const filePath = path.join(dir, file);
    let content = fs.readFileSync(filePath, 'utf8');
    const updated = content.replace(
      /\{\(([a-zA-Z0-9_]+),\s*_index\)\s*=>\s*\{\s*const\s+index\s*=\s*_index\(\);([\s\S]*?)(?=\n\s*\}\}\s*\n\s*<\/For>)/g,
      (match, itemVar, body) => {
        if (!/\bindex\b/.test(body)) {
          return `{(${itemVar}) => {${body}`;
        }
        return match;
      }
    );
    if (updated !== content) {
      fs.writeFileSync(filePath, updated, 'utf8');
      console.log(`Cleaned up unused index in ${filePath}`);
    }
  }
}

fixSolidUnusedIndex(path.join(__dirname, 'dist', 'solid', 'src', 'components'));
fixSolidUnusedIndex(path.join(__dirname, 'docs', 'v0', 'dist', 'solid', 'src', 'components'));

